/* Пределы значений записи. Один источник для двух сторон: ядро (session.ts)
   проверяет по ним ввод, а разбор сохранённого текста (state/storage.ts)
   по ним же решает, что запись цела. Если ввод пропустил значение, которое
   разбор отвергает, запись выпадает при следующей загрузке, поэтому пределы
   живут здесь, а не в двух местах.

   Точность хранения: секунды (подхода, удержания, кардио, отдыха) и пульс -
   целые. Ввод приводит их к целым округлением, разбор целых и ждёт. */

/** Вес снаряда и помощь в подходе, кг: больше нуля и не больше этого. */
export const LOAD_MAX_KG = 1000
/** Вес тела в настройках, кг. */
export const BODY_WEIGHT_MAX_KG = 400
/** Отдых между подходами, секунды: от 0 до этого. */
export const REST_MAX_SEC = 3600
/** Запас повторов (RIR): целое от 0 до этого. */
export const RIR_MAX = 5
/** Пульс, хранимый в записи и настройках: целое в этих пределах. */
export const HR_MIN = 20
export const HR_MAX = 260
/** Ощущаемая нагрузка внешнего занятия: целое в этих пределах. */
export const RPE_MIN = 1
export const RPE_MAX = 10

/** Границы своего интервального протокола (раздел 3.4 плана), целые секунды и раунды. */
export const CUSTOM_PROTOCOL_LIMITS = {
  workSec: [5, 600],
  restSec: [0, 600],
  rounds: [1, 30],
  warmupSec: [0, 900],
  cooldownSec: [0, 600],
} as const

/** Отметка времени записи: конечное неотрицательное число миллисекунд. */
export function isMillis(value: unknown): value is number {
  return typeof value === 'number' && Number.isFinite(value) && value >= 0
}
